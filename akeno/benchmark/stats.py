"""Frame-time statistics and PresentMon CSV parsing."""

from __future__ import annotations

import csv
import io
import math
import statistics
from dataclasses import dataclass

from akeno.core.models import FrameStats

FRAME_COLUMNS = ("MsBetweenPresents", "msBetweenPresents", "MsBetweenAppStart", "MsBetweenDisplayChange")


class CsvError(ValueError):
    pass


@dataclass
class ParsedCsv:
    frametimes_ms: list[float]
    process_names: list[str]
    column: str
    runtimes: list[str]


def parse_presentmon_csv(text: str, process_name: str | None = None) -> ParsedCsv:
    reader = csv.DictReader(io.StringIO(text))
    if not reader.fieldnames:
        raise CsvError("The CSV file is empty.")
    col = next((c for c in FRAME_COLUMNS if c in reader.fieldnames), None)
    if col is None:
        raise CsvError("No frame-time column (MsBetweenPresents / MsBetweenAppStart) found; not a PresentMon CSV.")
    app_col = next((c for c in ("Application", "ProcessName") if c in reader.fieldnames), None)
    ftype_col = "FrameType" if "FrameType" in reader.fieldnames else None
    rt_col = "PresentRuntime" if "PresentRuntime" in reader.fieldnames else ("Runtime" if "Runtime" in reader.fieldnames else None)
    times: list[float] = []
    names: set[str] = set()
    runtimes: set[str] = set()
    for row in reader:
        app = (row.get(app_col) or "") if app_col else ""
        if process_name and app and app.lower() != process_name.lower():
            continue
        if ftype_col and (row.get(ftype_col) or "").strip().lower() not in ("", "application", "na", "notset"):
            continue   # exclude frames generated by frame generation: measure rendered frames
        raw = (row.get(col) or "").strip()
        try:
            v = float(raw)
        except ValueError:
            continue
        if not math.isfinite(v) or v <= 0 or v > 5000:
            continue
        times.append(v)
        if app:
            names.add(app)
        if rt_col and row.get(rt_col):
            runtimes.add(row[rt_col])
    return ParsedCsv(times, sorted(names), col, sorted(runtimes))


def percentile(sorted_vals: list[float], p: float) -> float:
    if not sorted_vals:
        raise ValueError("empty")
    k = (len(sorted_vals) - 1) * p / 100.0
    f, c = math.floor(k), math.ceil(k)
    if f == c:
        return sorted_vals[int(k)]
    return sorted_vals[f] + (sorted_vals[c] - sorted_vals[f]) * (k - f)


def compute(frametimes_ms: list[float], drop_first_s: float = 0.0) -> FrameStats:
    """Statistics over rendered frames.

    1% / 0.1% low FPS are computed as the average FPS of the slowest 1% / 0.1% of frames (by frame time),
    the convention used by CapFrameX and most reviewers. 0.1% low needs at least 1000 frames.
    """
    ft = list(frametimes_ms)
    if drop_first_s > 0:
        acc = 0.0
        i = 0
        while i < len(ft) and acc < drop_first_s * 1000:
            acc += ft[i]
            i += 1
        ft = ft[i:]
    if len(ft) < 30:
        raise ValueError("Not enough frames for meaningful statistics (need at least 30).")
    total_ms = sum(ft)
    s = sorted(ft)
    n = len(s)
    worst1 = s[-max(1, n // 100):]
    low1 = 1000.0 / (sum(worst1) / len(worst1))
    low01 = None
    if n >= 1000:
        worst01 = s[-max(1, n // 1000):]
        low01 = 1000.0 / (sum(worst01) / len(worst01))
    med = statistics.median(s)
    stutters = sum(1 for v in ft if v > 2 * med)
    return FrameStats(
        frames=n, duration_s=round(total_ms / 1000.0, 3), avg_fps=round(n * 1000.0 / total_ms, 2),
        avg_frametime_ms=round(total_ms / n, 3), median_frametime_ms=round(med, 3),
        p95_frametime_ms=round(percentile(s, 95), 3), p99_frametime_ms=round(percentile(s, 99), 3),
        low_1pct_fps=round(low1, 2), low_01pct_fps=round(low01, 2) if low01 else None,
        stdev_frametime_ms=round(statistics.pstdev(ft), 3), stutter_ratio=round(stutters / n, 4),
    )


def consistency_label(stats: FrameStats) -> str:
    """Frame-time consistency from the measured 1%-low/average ratio and stutter share (documented in README)."""
    ratio = stats.low_1pct_fps / stats.avg_fps if stats.avg_fps else 0
    if ratio >= 0.75 and stats.stutter_ratio <= 0.01:
        return "good"
    if ratio >= 0.5 and stats.stutter_ratio <= 0.05:
        return "fair"
    return "poor"
